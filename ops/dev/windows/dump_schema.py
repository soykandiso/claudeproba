"""`ops/dump-schema.sh` for the Windows dev host, where there is no Docker. Not used anywhere else.

    uv run python ops/dev/windows/dump_schema.py

Runs the conda-forge `pg_dump` (docs/handoff.md §5) against the development database with the
script's own flags, then makes its output read as the VPS's would: the `\\restrict` nonce
dropped (as the script does), Windows line endings removed, and the server version written as
the Debian build the VPS runs, so a regeneration here diffs only where the schema changed.
"""

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PG_DUMP = Path(os.environ["LOCALAPPDATA"]) / "grants-pg" / "Library" / "bin" / "pg_dump.exe"
DEBIAN = " (Debian 16.15-1.pgdg12+2)"
HEADER = (
    "-- Generated by ops/dump-schema.sh from the live database. Do not edit.\n"
    "-- Source of truth: app/models/ and migrations/. Rationale: docs/data-model.md.\n"
    "-- Regenerate after every migration:  ./ops/dump-schema.sh\n\n"
)


def main() -> None:
    sys.path.insert(0, str(ROOT))
    from app.config import load_settings

    url = load_settings().database_url.replace("postgresql+psycopg://", "postgresql://")
    dumped = subprocess.run(
        [str(PG_DUMP), "--schema-only", "--no-owner", "--no-privileges", "--no-comments", url],
        check=True,
        capture_output=True,
        timeout=60,
    ).stdout.decode("utf-8")
    lines = []
    for line in dumped.replace("\r", "").splitlines(keepends=True):
        if line.startswith(("\\restrict ", "\\unrestrict ")):
            continue
        if line.startswith(("-- Dumped from database version", "-- Dumped by pg_dump version")):
            line = line.rstrip("\n").removesuffix(DEBIAN) + DEBIAN + "\n"
        lines.append(line)
    out = ROOT / "docs" / "schema.sql"
    out.write_text(HEADER + "".join(lines), encoding="utf-8", newline="\n")
    print(f"docs/schema.sql regenerated ({len(lines) + 4} lines)")


if __name__ == "__main__":
    main()
